/**
 * Returns the display name for a product in the given language. Falls back
 * to the original (English) name whenever the language is English or we
 * don't have a translation for this id yet — so live-catalog products added
 * later by the admin never render blank, they just show in English until a
 * translation is added here.
 */
export function translateProductName(id: string, name: string, lang: Language): string {
  if (lang === 'en') return name;
  const t = PRODUCT_NAME_TRANSLATIONS[id];
  if (!t) return name;
  return t[lang] ?? name;
}
